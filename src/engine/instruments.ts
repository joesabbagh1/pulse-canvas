import type { SynthMode, SynthWave } from './synth';

// General MIDI's 128 melodic programs, a small drum kit, the club kit, an acid
// bass, and the eight voices already in the engine. `voice` chooses the synth.
// A pitched drum still carries `tune`: the player uses the note, and `tune` is
// only the fallback. On top of the catalog sit the piece's synth machines
// (see engine/synth.ts): user-editable instruments registered at runtime, which
// instrumentById resolves exactly like a built-in.

export const CATEGORIES = [
  { id: 'keys', label: 'Keyboards', hue: 45 },
  { id: 'bowed', label: 'Bowed strings', hue: 18 },
  { id: 'plucked', label: 'Plucked strings', hue: 330 },
  { id: 'winds', label: 'Winds', hue: 175 },
  { id: 'brass', label: 'Brass', hue: 28 },
  { id: 'percussion', label: 'Percussion', hue: 12 },
  { id: 'voice', label: 'Voice', hue: 280 },
  { id: 'synths', label: 'Synths', hue: 200 },
] as const;

export type CategoryId = (typeof CATEGORIES)[number]['id'];
export type BuiltInVoice = 'tone' | 'pluck' | 'bass' | 'jawharp' | 'khuur' | 'kick' | 'snare' | 'hat';
export type DrumHit = 'membrane' | 'snare' | 'hat' | 'cymbal' | 'clap' | 'shake' | 'wood' | 'noise';

type Common = {
  id: string;
  name: string;
  /** Under the note name on the block. Empty shows only the note. At most 7 characters. */
  short: string;
  category: CategoryId;
  hint: string;
  pitched: boolean;
  /** Growing a block off this one steps the new block up one scale degree. */
  steps: boolean;
};

export type Instrument = Common & (
  | { voice: BuiltInVoice }
  | {
      voice: 'sustain';
      wave: 'sine' | 'triangle' | 'square' | 'sawtooth' | 'fatsawtooth';
      attack: number;
      decay: number;
      sustain: number;
      release: number;
      cutoff: number;
      gain: number;
      spread?: number;
      fifth?: boolean;
    }
  | {
      voice: 'pluck';
      dampening: number;
      resonance: number;
      attackNoise: number;
      release: number;
      gain: number;
    }
  | {
      voice: 'bow';
      attack: number;
      cutoff: number;
      vibrato: number;
      drone: boolean;
      gain: number;
    }
  | {
      voice: 'blow';
      wave: 'square' | 'sawtooth' | 'triangle';
      attack: number;
      sustain: number;
      release: number;
      breath: number;
      q: number;
      vibrato: number;
      gain: number;
      drone?: boolean;
    }
  | {
      voice: 'mallet';
      decay: number;
      ratio: number;
      index: number;
      gain: number;
    }
  | {
      voice: 'drum';
      hit: DrumHit;
      decay: number;
      tune: number;
      gain: number;
    }
  | {
      voice: 'machine';
      hit: 'kick' | 'hat' | 'open' | 'clap' | 'rim';
      gain: number;
    }
  | {
      voice: 'acid';
      wave: 'sawtooth' | 'square';
      gain: number;
    }
  | {
      voice: 'synth';
      wave: SynthWave;
      cutoff: number;
      q: number;
      attack: number;
      decay: number;
      sustain: number;
      release: number;
      mode: SynthMode;
      glide: number;
      gain: number;
    }
);

